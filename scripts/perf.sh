#!/usr/bin/env bash
# shellcheck disable=SC2016,SC2329
set -euo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
backend="${root}/backend"
qa_log="${PERF_QA_LOG:-${root}/docs/plan/QA_LOG.md}"
qa_section="${PERF_QA_SECTION:-## M5 Reports and dashboard}"
scratch_db="${PERF_DB:-finance_perf}"
php_memory_limit="${PERF_PHP_MEMORY_LIMIT:-1G}"

export DB_CONNECTION=pgsql
export DB_HOST="${DB_HOST:-127.0.0.1}"
export DB_PORT="${DB_PORT:-5432}"
export DB_USERNAME="${DB_USERNAME:-finance}"
export DB_PASSWORD="${DB_PASSWORD:-finance}"
export APP_ENV=local

if [[ ! "$scratch_db" =~ ^[a-z_][a-z0-9_]*$ ]] || [[ "$scratch_db" == "finance" || "$scratch_db" == "finance_test" ]]; then
  printf 'perf: PERF_DB must be a scratch database name, got "%s"\n' "$scratch_db" >&2
  exit 2
fi

work="$(mktemp -d)"

admin_sql() {
  php -r '
    $pdo = new PDO(
        sprintf("pgsql:host=%s;port=%s;dbname=postgres", getenv("DB_HOST"), getenv("DB_PORT")),
        getenv("DB_USERNAME"),
        getenv("DB_PASSWORD"),
        [PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION],
    );
    $result = $pdo->query($argv[1]);
    echo $result->columnCount() > 0 ? (string) $result->fetchColumn() : "";
  ' "$1"
}

drop_scratch_db() {
  admin_sql "DROP DATABASE IF EXISTS ${scratch_db} WITH (FORCE)" >/dev/null || true
  rm -rf "$work"
}

trap drop_scratch_db EXIT

in_scratch_db() {
  (cd "$backend" && DB_DATABASE="$scratch_db" "$@")
}

now_ms() {
  php -r 'echo intdiv(hrtime(true), 1_000_000);'
}

printf 'perf: preparing scratch database %s on %s:%s\n' "$scratch_db" "$DB_HOST" "$DB_PORT"
postgres_version="$(admin_sql 'SHOW server_version')"
admin_sql "DROP DATABASE IF EXISTS ${scratch_db} WITH (FORCE)" >/dev/null
admin_sql "CREATE DATABASE ${scratch_db}" >/dev/null

in_scratch_db php artisan migrate:fresh --force --no-interaction >/dev/null

printf 'perf: seeding PerformanceSeeder\n'
seed_started="$(now_ms)"
seed_status=0
in_scratch_db php -d memory_limit="$php_memory_limit" artisan db:seed --class='Database\Seeders\PerformanceSeeder' --force --no-interaction || seed_status=$?
seed_ms=$(( $(now_ms) - seed_started ))

movement_count="$(in_scratch_db php artisan tinker --execute='echo DB::table("transactions")->whereNull("deleted_at")->count();' 2>/dev/null | tail -n 1 || echo '?')"

ledger_status=0
if [[ "$seed_status" -eq 0 ]]; then
  in_scratch_db php artisan app:ledger:verify >"${work}/ledger.txt" 2>&1 || ledger_status=$?
else
  ledger_status=1
  printf 'skipped because the seed failed' >"${work}/ledger.txt"
fi
ledger_output="$(tr '\n' ' ' <"${work}/ledger.txt" | sed 's/[[:space:]]*$//')"

printf 'perf: running Pest --group=perf\n'
pest_status=0
(cd "$backend" && PAO_DISABLE=1 php -d memory_limit="$php_memory_limit" artisan test --group=perf --colors=never) 2>&1 | tee "${work}/pest.txt" || pest_status=${PIPESTATUS[0]}
pest_summary="$(grep -E '^[[:space:]]*Tests:' "${work}/pest.txt" | tail -n 1 | sed -E 's/^[[:space:]]+//; s/[[:space:]]+/ /g' || true)"

results_table="$(grep -E '^month_start_day=[0-9]+ \{' "${work}/pest.txt" | php -r '
  $rows = [];
  while (($line = fgets(STDIN)) !== false) {
      [$period, $json] = explode(" ", trim($line), 2);
      $day = substr($period, strlen("month_start_day="));
      foreach (json_decode($json, true, flags: JSON_THROW_ON_ERROR) as $endpoint => $timing) {
          $rows[] = sprintf("| %s | %s | %d | %d | %s |", $endpoint, $day, $timing["p50"], $timing["p95"], $timing["p95"] < 300 ? "pass" : "FAIL");
      }
  }
  echo implode(PHP_EOL, $rows);
' || true)"

status_word() {
  [[ "$1" -eq 0 ]] && echo pass || echo "FAIL (exit $1)"
}

entry="${work}/entry.md"
{
  printf '### %s perf (%s %s, PHP %s, PostgreSQL %s)\n\n' \
    "$(date '+%Y-%m-%d %H:%M %Z')" "$(uname -s)" "$(uname -m)" "$(php -r 'echo PHP_VERSION;')" "$postgres_version"
  printf 'Generated by `make perf` (`scripts/perf.sh`) at commit `%s`.\n\n' \
    "$(git -C "$root" rev-parse --short HEAD 2>/dev/null || echo unknown)$(git -C "$root" diff --quiet HEAD -- 2>/dev/null || echo '+dirty')"
  printf '| Check | Command | Result |\n|---|---|---|\n'
  printf '| Scratch seed | `php artisan db:seed --class=PerformanceSeeder` on `%s` | %s; %s live movements in %d ms |\n' \
    "$scratch_db" "$(status_word "$seed_status")" "$movement_count" "$seed_ms"
  printf '| Ledger invariants | `php artisan app:ledger:verify` on `%s` | %s; %s |\n' \
    "$scratch_db" "$(status_word "$ledger_status")" "${ledger_output:-no output}"
  printf '| Perf group | `php artisan test --group=perf` on `finance_test` | %s; %s |\n\n' \
    "$(status_word "$pest_status")" "${pest_summary:-no summary}"
  if [[ -n "$results_table" ]]; then
    printf '| Endpoint | month_start_day | p50 ms | p95 ms | p95 < 300 ms |\n|---|---|---|---|---|\n'
    printf '%s\n' "$results_table"
  else
    printf 'No per-endpoint timings were reported by the perf group.\n'
  fi
} >"$entry"

if ! grep -qxF "$qa_section" "$qa_log"; then
  printf '\n%s\n' "$qa_section" >>"$qa_log"
fi

awk -v section="$qa_section" -v entry="$entry" '
  function flush() {
    if (!blank) print ""
    while ((getline line < entry) > 0) print line
    close(entry)
    done = 1
  }
  $0 == section { inside = 1; print; blank = 0; next }
  inside && !done && /^## / { flush(); print ""; inside = 0 }
  { print; blank = ($0 == "") }
  END { if (!done) flush() }
' "$qa_log" >"${work}/qa_log.md"
cat "${work}/qa_log.md" >"$qa_log"

printf 'perf: results appended to %s under "%s"\n' "$qa_log" "$qa_section"

overall=0
for status in "$seed_status" "$ledger_status" "$pest_status"; do
  if [[ "$status" -ne 0 ]]; then
    overall=1
  fi
done
exit "$overall"
